  var mailOriginal = {};
  function enc(s) { return encodeURIComponent(s).replace(/'/g, '%27'); }
  function subjectOf(href) {
    var m = /[?&]subject=([^&]*)/.exec(href);
    if (!m) return null;
    try { return decodeURIComponent(m[1]); } catch (e) { return null; }
  }
  function mailKind(href) {
    var subject = subjectOf(href);
    if (subject === null) return null;
    for (var k in MAIL) {
      for (var i = 0; i < LANGS.length; i++) { if (MAIL[k][LANGS[i]][0] === subject) return k; }
    }
    return null;
  }
  function mailHref(kind, lang) {
    if (lang === 'en' && mailOriginal[kind]) return mailOriginal[kind];
    var m = MAIL[kind][lang] || MAIL[kind].en;
    return 'mailto:support@neldo.app?subject=' + enc(m[0]) + (m[1] ? '&body=' + enc(m[1].replace(/\n/g, '\r\n')) : '');
  }
  // Keep the page's own EN email hrefs (exact bytes) so switching back to EN restores them.
  function rememberMail() {
    document.querySelectorAll('a[href^="mailto:"]').forEach(function (a) {
      var href = a.getAttribute('href'), subject = subjectOf(href);
      for (var k in MAIL) { if (MAIL[k].en[0] === subject && !mailOriginal[k]) mailOriginal[k] = href; }
    });
  }
  function localizeLinks(lang) {
    document.querySelectorAll('a[href]').forEach(function (a) {
      var href = a.getAttribute('href'), m = LEGAL.exec(href);
      if (m) {
        var next = m[1] + (lang === 'en' ? '' : '-' + lang) + '.html' + (m[2] || '');
        if (next !== href) a.setAttribute('href', next);
        return;
      }
      var p = PAGE.exec(href);
      if (p) {
        var page = p[1] + (lang === 'en' ? '' : '?lang=' + lang) + (p[2] || '');
        if (page !== href) a.setAttribute('href', page);
        return;
      }
      if (href.indexOf('mailto:') !== 0) return;
      var kind = mailKind(href);
      if (kind) { var h = mailHref(kind, lang); if (h !== href) a.setAttribute('href', h); }
    });
  }

  function setLang(lang, opts) {
    var l = LANGS.indexOf(lang) > -1 ? lang : 'en';
    current = l;
    document.documentElement.lang = l;
    apply(document);
    localizeLinks(l);
    var sel = document.querySelector('[data-lang-select]');
    if (sel && sel.value !== l) sel.value = l;
    if (!opts || !opts.silent) {
      try { sessionStorage.setItem('neldo-lang', l); } catch (e) { /* per-page only */ }
      try {
        var url = new URL(location.href);
        if (l === 'en') url.searchParams.delete('lang'); else url.searchParams.set('lang', l);
        history.replaceState(null, '', url.pathname + url.search + url.hash);
      } catch (e) { /* file:// or old browser */ }
    }
    document.dispatchEvent(new CustomEvent('neldo:lang', { detail: { lang: l } }));
  }

  window.NeldoI18n = { t: function (key) { return t(key); }, apply: apply, setLang: setLang, lang: function () { return current; } };

  function init() {
    var lang = null;
    try { lang = new URLSearchParams(location.search).get('lang'); } catch (e) {}
    if (LANGS.indexOf(lang) < 0) { try { lang = sessionStorage.getItem('neldo-lang'); } catch (e) { lang = null; } }
    rememberMail();
    var sel = document.querySelector('[data-lang-select]');
    if (sel) sel.addEventListener('change', function () { setLang(sel.value); });
    if (LANGS.indexOf(lang) > -1 && lang !== 'en') setLang(lang, { silent: true });
    else if (sel) sel.value = 'en';
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();

