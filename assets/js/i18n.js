  function t(key, lang) {
    var l = lang || current;
    if (DICT[l] && Object.prototype.hasOwnProperty.call(DICT[l], key)) return DICT[l][key];
    if (Object.prototype.hasOwnProperty.call(DICT.en, key)) return DICT.en[key];
    return null;
  }

  function apply(scope) {
    var rootEl = scope || document;
    rootEl.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = t(el.getAttribute('data-i18n'));
      if (v !== null && el.textContent !== v) el.textContent = v;
    });
    rootEl.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var v = t(el.getAttribute('data-i18n-html'));
      if (v !== null && el.innerHTML !== v) el.innerHTML = v;
    });
    rootEl.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var i = pair.indexOf(':');
        if (i < 1) return;
        var attr = pair.slice(0, i).trim(), v = t(pair.slice(i + 1).trim());
        if (v !== null) el.setAttribute(attr, v);
      });
    });
  }

